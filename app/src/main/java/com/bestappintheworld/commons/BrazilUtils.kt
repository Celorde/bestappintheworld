        fun calculateStateClick(x: Int, y: Int, brazilStatesMap: Bitmap, matrix: Matrix) : BrazilianStates {
            val values = FloatArray(9)
            matrix.getValues(values)

            val scaleX = values[Matrix.MSCALE_X]
            val scaleY = values[Matrix.MSCALE_Y]
            val transX = values[Matrix.MTRANS_X]
            val transY = values[Matrix.MTRANS_Y]

            val scaledX = ((x - transX) / scaleX).toInt()
            val scaledY = ((y - transY) / scaleY).toInt()

            if (scaledX in 0 until brazilStatesMap.width && scaledY in 0 until brazilStatesMap.height) {
                val colorPixel = brazilStatesMap[scaledX, scaledY]
                val hex = String.format("#%06X", 0xFFFFFF and colorPixel)

                val clickedState = brazilianStateColorMap[hex]

                return if (colorPixel != 0 && clickedState == null) {
                    BrazilianStates.DIVIDER
                } else {
                    clickedState ?: BrazilianStates.NONE
                }
            }

            return BrazilianStates.NONE
        }
    }

